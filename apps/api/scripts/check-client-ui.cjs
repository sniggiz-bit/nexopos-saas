const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const { chromium } = require('/tmp/ui-check/node_modules/playwright');
const origin = 'http://release-web';
const password = 'Fixture-password-1842';
async function auth(page, token, user) {
  await page.goto(origin);
  await page.evaluate(({ token, user }) => {
    localStorage.clear(); localStorage.setItem('token', token); localStorage.setItem('user', JSON.stringify(user));
  }, { token, user });
}
(async () => {
  const fixture = JSON.parse(await fs.readFile('/checks-results/context.json', 'utf8'));
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'America/Santiago' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await auth(page, fixture.rootToken, fixture.rootUser);
    await page.goto(origin + '/admin/tenants/' + fixture.customerId);
    await page.getByRole('heading', { name: 'ClientB', exact: true }).waitFor();
    await page.screenshot({ path: '/checks-results/client-record-desktop.png', fullPage: true });
    await page.getByRole('tab', { name: 'Usuarios', exact: true }).click();
    await page.getByRole('button', { name: 'Agregar usuario' }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nombre', { exact: true }).fill('Usuario de prueba visual');
    await dialog.getByLabel('Correo', { exact: true }).fill('ui-' + Date.now() + '@example.invalid');
    await dialog.getByLabel('Contraseña inicial', { exact: true }).fill(password);
    await dialog.getByRole('button', { name: 'Guardar usuario', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('heading', { name: 'Usuario de prueba visual', exact: true }).waitFor();
    console.log('PASS: browser creates a customer user through the real form');
    await page.getByRole('tab', { name: 'Sucursales', exact: true }).click();
    await page.getByRole('button', { name: 'Crear sucursal', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nombre', { exact: true }).fill('Sucursal de prueba visual');
    await dialog.getByLabel('Dirección', { exact: true }).fill('Dirección ficticia 123');
    assert.equal(await dialog.getByLabel('Habilitada para operar').isChecked(), false);
    await dialog.getByRole('button', { name: 'Guardar sucursal' }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('heading', { name: 'Sucursal de prueba visual' }).waitFor();
    await page.getByRole('button', { name: 'Habilitar', exact: true }).click();
    await page.getByRole('button', { name: 'Habilitar', exact: true }).waitFor({ state: 'hidden' });
    console.log('PASS: browser creates and enables an additional branch as superadmin');
    await page.getByRole('tab', { name: 'Servicios y módulos', exact: true }).click();
    const quotes = page.getByRole('switch', { name: 'Habilitar QUOTES', exact: true });
    await quotes.waitFor();
    if (await quotes.getAttribute('aria-checked') === 'true') await quotes.click();
    await page.getByRole('button', { name: 'Guardar servicios', exact: true }).click();
    await page.getByText('Servicios actualizados para este cliente.', { exact: true }).waitFor();
    assert.equal(await quotes.getAttribute('aria-checked'), 'false');
    await quotes.locator('..').getByRole('button', { name: 'Usar base', exact: true }).click();
    await page.getByRole('button', { name: 'Guardar servicios', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Habilitar QUOTES"]')?.getAttribute('aria-checked') === 'true');
    console.log('PASS: browser disables a module and restores its inherited access');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('tab', { name: 'Ficha general', exact: true }).click();
    await page.screenshot({ path: '/checks-results/client-record-mobile.png', fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Customer record overflows the mobile viewport');
    await page.getByRole('tab', { name: 'Acciones', exact: true }).click();
    await page.getByRole('button', { name: 'Revisar eliminación' }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Tu contraseña de superadmin').waitFor();
    assert(await dialog.getByRole('button', { name: 'Eliminar cuenta permanentemente' }).isDisabled());
    await page.screenshot({ path: '/checks-results/client-deletion-confirmation.png', fullPage: true });
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    console.log('PASS: deletion remains blocked until explicit confirmation and password');
    const created = await page.request.post(origin + '/api/auth/register-tenant', { data: { companyName: 'Cliente de prueba de eliminación', userName: 'Usuario ficticio', email: 'delete-ui-' + Date.now() + '@example.invalid', phone: '+56900000000', password } });
    assert.equal(created.status(), 201);
    const temporary = await created.json();
    await page.goto(origin + '/admin/tenants/' + temporary.tenant.id + '?tab=actions');
    await page.getByRole('button', { name: 'Revisar eliminación' }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Tu contraseña de superadmin').waitFor();
    const preview = await page.request.get(origin + '/api/admin/tenants/' + temporary.tenant.id + '/deletion-preview', { headers: { Authorization: 'Bearer ' + fixture.rootToken } });
    const details = await preview.json();
    await dialog.locator('input[autocomplete="off"]').fill(details.confirmation);
    await dialog.getByLabel('Tu contraseña de superadmin').fill(password);
    await dialog.getByRole('checkbox').check();
    await dialog.getByRole('button', { name: 'Eliminar cuenta permanentemente' }).click();
    await page.waitForURL(origin + '/admin/tenants');
    const missing = await page.request.get(origin + '/api/admin/tenants/' + temporary.tenant.id, { headers: { Authorization: 'Bearer ' + fixture.rootToken } });
    assert.equal(missing.status(), 404);
    console.log('PASS: the full deletion form removes only the explicitly confirmed fixture');
    await auth(page, fixture.customerToken, fixture.customerUser);
    await page.goto(origin + '/dashboard/branches');
    await page.getByRole('heading', { name: 'Sucursales', exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Sucursal de prueba visual', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: /Nueva Sucursal|Crear sucursal/i }).count(), 0);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Customer branch page overflows on mobile');
    await page.screenshot({ path: '/checks-results/customer-branches-mobile.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: customer branch page is read-only, responsive and free of browser errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
